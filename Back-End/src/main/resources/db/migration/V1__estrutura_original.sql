CREATE TABLE usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(255) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE, senha VARCHAR(255) NOT NULL, telefone VARCHAR(255),
 role VARCHAR(255) NOT NULL, data_cadastro TIMESTAMP
);
CREATE TABLE categorias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(255) NOT NULL UNIQUE,
 descricao VARCHAR(255), icone VARCHAR(255)
);
CREATE TABLE produtos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(255) NOT NULL,
 descricao VARCHAR(2000), preco NUMERIC(10,2) NOT NULL, preco_promocional NUMERIC(10,2),
 estoque INTEGER NOT NULL, imagem_url VARCHAR(1000), categoria_id BIGINT NOT NULL REFERENCES categorias(id),
 destaque BOOLEAN, ativo BOOLEAN, data_cadastro TIMESTAMP
);
CREATE TABLE enderecos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cep VARCHAR(255) NOT NULL,
 rua VARCHAR(255) NOT NULL, numero VARCHAR(255) NOT NULL, complemento VARCHAR(255),
 bairro VARCHAR(255) NOT NULL, cidade VARCHAR(255) NOT NULL, estado VARCHAR(255) NOT NULL,
 usuario_id BIGINT REFERENCES usuarios(id)
);
CREATE TABLE carrinhos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id)
);
CREATE TABLE itens_carrinho (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 carrinho_id BIGINT NOT NULL REFERENCES carrinhos(id), produto_id BIGINT NOT NULL REFERENCES produtos(id),
 quantidade INTEGER NOT NULL
);
CREATE TABLE favoritos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id), produto_id BIGINT NOT NULL REFERENCES produtos(id),
 data_adicionado TIMESTAMP, UNIQUE(usuario_id, produto_id)
);
CREATE TABLE pedidos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero_pedido VARCHAR(255) NOT NULL UNIQUE, usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 data_pedido TIMESTAMP, status VARCHAR(255) NOT NULL,
 valor_subtotal NUMERIC(10,2) NOT NULL, valor_desconto NUMERIC(10,2), valor_frete NUMERIC(10,2),
 valor_total NUMERIC(10,2) NOT NULL, cupom_aplicado VARCHAR(255), cep_entrega VARCHAR(255),
 endereco_entrega VARCHAR(255), numero_entrega VARCHAR(255), complemento_entrega VARCHAR(255),
 bairro_entrega VARCHAR(255), cidade_entrega VARCHAR(255), estado_entrega VARCHAR(255)
);
CREATE TABLE itens_pedido (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id BIGINT NOT NULL REFERENCES pedidos(id), produto_id BIGINT NOT NULL REFERENCES produtos(id),
 quantidade INTEGER NOT NULL, preco_unitario NUMERIC(10,2) NOT NULL, subtotal NUMERIC(10,2) NOT NULL
);
CREATE TABLE pagamentos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedidos(id), forma_pagamento VARCHAR(255) NOT NULL,
 status VARCHAR(255) NOT NULL, valor NUMERIC(10,2) NOT NULL, data_pagamento TIMESTAMP,
 codigo_pix VARCHAR(2000), codigo_barras_boleto VARCHAR(100), cartao_ultimos_digitos VARCHAR(255), parcelas INTEGER
);
CREATE TABLE mensagens (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(255), email VARCHAR(255), telefone VARCHAR(255), assunto VARCHAR(255),
 conteudo VARCHAR(3000) NOT NULL, data_envio TIMESTAMP, respondida BOOLEAN, resposta VARCHAR(255)
);
